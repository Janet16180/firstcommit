  function use(language) {
    current = language in TABLES ? language : "en";
  }

  function t(key, params = {}) {
    const entry = TABLES[current][key];
    if (entry === undefined) throw new RangeError(`no string for ${key}`);
    const text = typeof entry === "string" ? entry : params.count === 1 ? entry.one : entry.other;
    return text.replace(/\{(\w+)\}/g, (whole, name) => (name in params ? String(params[name]) : whole));
  }

  /* The string cut at its backticks: the odd pieces are commands. */
  const parts = (key, params) => t(key, params).split("`").map((piece, index) => (index % 2 ? { code: piece } : piece)).filter((piece) => piece !== "");

  const group = (prefix) => Object.fromEntries(Object.keys(TABLES[current]).filter((key) => key.startsWith(prefix)).map((key) => [key.slice(prefix.length), t(key)]));

  return { TABLES, use, t, parts, group, language: () => current };
